export function expandQuery(query: string): string[] {
  const terms = new Set<string>([query]);
  for (const [term, synonyms] of Object.entries(SYNONYMS)) {
    if (query.includes(term)) {
      for (const s of synonyms) terms.add(s);
    }
  }
  return [...terms];
}
