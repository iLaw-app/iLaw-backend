export function expandQuery(query: string): string[] {
  const terms = new Set<string>([query]);
  for (const group of SYNONYM_GROUPS) {
    if (group.some((term) => query.includes(term))) {
      group.forEach((term) => terms.add(term));
    }
  }
  return [...terms];
}
